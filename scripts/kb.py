#!/usr/bin/env python3
"""Git-native Markdown knowledge retrieval: exact IDs + ranked FTS5 sections."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sqlite3
import subprocess
import sys
from contextlib import closing
from pathlib import Path
from typing import NamedTuple
from urllib.parse import unquote

FRONTMATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)
FIELDS = ("id", "title", "summary", "aliases", "tags", "related")
KEY_LINE = re.compile(r"([^\W\d][\w .-]*?)[ \t]*:(?:[ \t]+(.*))?$")
QUOTED = re.compile(r'"(?:[^"\\]|\\.)*"|\'(?:[^\']|\'\')*\'')
FLOW_ITEM = re.compile(r'[ \t]*("(?:[^"\\]|\\.)*"|\'(?:[^\']|\'\')*\'|[^,\]"\'\s][^,\]]*?)?'
                       r'[ \t]*([,\]])')
COMMENT_TAIL = re.compile(r"(?:[ \t]+#.*)?")
# A closing run of #s only counts when a space precedes it, so "# C#" keeps its "#".
HEADING = re.compile(r"^(#{1,6})[ \t]+(.+?)(?:[ \t]+#+)?[ \t]*$")
WORD = re.compile(r"\w+", re.UNICODE)
SLUG = re.compile(r"[^\w-]+", re.UNICODE)
RESERVED = ("index.md", "log.md")  # OKF navigation and change-history files; never indexed
CATALOG_MARK = "<!-- Generated by scripts/kb.py build"
QMD_COLLECTION = "sections"  # the one collection in kb's own QMD index
RRF_K = 60  # reciprocal rank fusion constant, the value QMD's own hybrid search uses


class Section(NamedTuple):
    heading: str  # e.g. "Configuration"
    heading_path: str  # the heading with its parents, e.g. "Postgres > Configuration"
    slug: str  # unique within the document
    content: str


def plain(text: str) -> str:
    """A plain YAML scalar without its trailing comment (a # at the start or after a space)."""
    return re.split(r"(?:^|[ \t])#", text, maxsplit=1)[0].strip()


def scalar(text: str, here: str) -> str | None:
    """A quoted or plain YAML scalar; plain null spellings become None."""
    if text[:1] not in ("'", '"'):
        value = plain(text)
        return None if value in ("", "~", "null", "Null", "NULL") else value
    match = QUOTED.match(text)
    if not match or not COMMENT_TAIL.fullmatch(text, match.end()):
        raise ValueError(f"{here}: unterminated or malformed quoted text")
    quoted = match.group()
    if quoted[0] == "'":
        return quoted[1:-1].replace("''", "'")
    try:
        return json.loads(quoted, strict=False)  # JSON escapes are a subset of YAML's
    except ValueError:
        raise ValueError(f"{here}: unsupported escape in quoted text") from None


def flow_list(text: str, here: str) -> list:
    """A one-line YAML list such as `[a, "b, c", 'd']`."""
    items, pos = [], 1
    while True:
        match = FLOW_ITEM.match(text, pos)
        if not match:
            raise ValueError(f"{here}: a [...] list must close on the same line")
        pos = match.end()
        if match.group(1) is not None:
            items.append(scalar(match.group(1), here))
        elif match.group(2) == ",":
            raise ValueError(f"{here}: empty list item")
        if match.group(2) == "]":
            break
    if not COMMENT_TAIL.fullmatch(text, pos):
        raise ValueError(f"{here}: unexpected text after the list")
    return items


def parse_frontmatter(block: str, where: Path) -> dict:
    """Read the YAML subset used by knowledge files; keys other than FIELDS are skipped.

    Values are plain or quoted text, `[a, b]` or `- item` lists, or `|`/`>` text blocks.
    Anything else in a known field fails with its line number instead of being guessed.
    """
    data: dict = {}
    key, mode, lines = None, None, []  # mode: how indented lines below `key` are read
    for number, line in enumerate(block.split("\n"), 1):
        here = f"{where}: frontmatter line {number}"
        indented, stripped = line[:1] in (" ", "\t"), line.strip()
        if mode in ("|", ">"):
            if indented or not stripped:
                lines.append(stripped)
                continue
            data[key] = "\n".join(lines).strip() if mode == "|" else " ".join(filter(None, lines))
            mode = None
        if not stripped or stripped.startswith("#"):
            continue
        if mode == "skip" and (indented or stripped.startswith("-")):
            continue
        if mode == "plain" and indented:  # a plain value continued on the next line
            data[key] = f"{data[key]} {plain(stripped)}"
            continue
        if stripped == "-" or stripped.startswith("- "):
            if mode not in ("list", "empty"):
                raise ValueError(f"{here}: unexpected list item")
            data[key], mode = (data[key] or []) + [scalar(stripped[1:].strip(), here)], "list"
            continue
        if indented:
            if mode != "empty":
                raise ValueError(f"{here}: unexpected indented line")
            data[key], mode = plain(stripped), "plain"  # `key:` with its value on the next line
            continue
        match = KEY_LINE.match(line)
        if not match:
            raise ValueError(f"{here}: expected 'key: value'")
        key, value = match.group(1), (match.group(2) or "").strip()
        if key not in FIELDS:
            key, mode = None, "skip"
            continue
        if key in data:
            raise ValueError(f"{here}: duplicate key {key!r}")
        data[key], mode = None, "empty"
        if value[:1] == "[":
            data[key], mode = flow_list(value, here), None
        elif value[:1] in ("|", ">"):
            if not re.fullmatch(r"[|>][1-9+-]{0,2}", plain(value)):
                raise ValueError(f"{here}: unsupported block header {value!r}")
            mode, lines = value[0], []
        elif value[:1] in ("{", "&", "*", "!"):
            raise ValueError(f"{here}: unsupported YAML syntax {value[:1]!r}")
        elif value[:1] in ("'", '"'):
            data[key], mode = scalar(value, here), None
        elif plain(value):
            data[key], mode = scalar(value, here), "plain"
    if mode in ("|", ">"):
        data[key] = "\n".join(lines).strip() if mode == "|" else " ".join(filter(None, lines))
    return data


def parse_document(path: Path) -> tuple[dict, str]:
    raw = path.read_text(encoding="utf-8-sig")  # -sig drops a byte-order mark (Windows editors)
    match = FRONTMATTER.match(raw)
    if not match:
        raise ValueError(f"{path}: missing YAML frontmatter")
    metadata = parse_frontmatter(match.group(1), path)
    for field in ("id", "title", "summary"):
        if not isinstance(metadata.get(field), str) or not metadata[field].strip():
            raise ValueError(f"{path}: missing/invalid {field}")
    for field in ("aliases", "tags", "related"):
        val = metadata.get(field)
        if val is None:  # absent, or an empty `field:` line
            val = metadata[field] = []
        if not isinstance(val, list) or not all(isinstance(v, str) for v in val):
            raise ValueError(f"{path}: {field} must be a list of strings")
    if not re.fullmatch(r"[a-z0-9][a-z0-9._/-]*", metadata["id"]):
        raise ValueError(f"{path}: id must be lowercase path-safe ASCII")
    return metadata, raw[match.end():]


def sections(body: str) -> list[Section]:
    """Split on Markdown ATX headings, excluding fenced code blocks."""
    result: list[Section] = []
    trail: list[tuple[int, str]] = []  # (level, text) of the current heading and its parents
    lines: list[str] = []
    used: set[str] = set()
    fence_char, fence_len = "", 0

    def flush() -> None:
        nonlocal lines
        content = "".join(lines).strip()
        if content:
            heading = trail[-1][1] if trail else "Overview"
            base = SLUG.sub("-", heading.casefold()).strip("-") or "section"
            slug, number = base, 1
            while slug in used:  # also avoids clashing with a real heading such as "Example-2"
                number += 1
                slug = f"{base}-{number}"
            used.add(slug)
            heading_path = " > ".join(text for _, text in trail) or heading
            result.append(Section(heading, heading_path, slug, content))
        lines = []

    for line in body.splitlines(keepends=True):
        fence = re.match(r"^\s{0,3}(\x60{3,}|~{3,})", line)
        if fence:
            marker = fence.group(1)
            if not fence_char:
                fence_char, fence_len = marker[0], len(marker)
            elif marker[0] == fence_char and len(marker) >= fence_len:
                fence_char, fence_len = "", 0
        match = HEADING.match(line.rstrip("\r\n")) if not fence_char else None
        if match:
            flush()
            level = len(match.group(1))
            while trail and trail[-1][0] >= level:
                trail.pop()
            trail.append((level, match.group(2).strip()))
        else:
            lines.append(line)
    flush()
    return result or [Section("Overview", "Overview", "overview", "")]


def locations(root: Path) -> tuple[Path, Path]:
    return root / ".knowledge" / "index.json", root / ".knowledge" / "search.db"


def source_files(root: Path) -> list[Path]:
    """Markdown files under knowledge/. Directory symlinks are not followed."""
    folder = root / "knowledge"
    if not folder.is_dir():
        raise ValueError(f"Missing knowledge directory: {folder}")
    found = [Path(directory, name) for directory, _, names in os.walk(folder)
             for name in names if name.endswith(".md")]
    for path in found:
        if not path.resolve().is_relative_to(root):
            rel = path.relative_to(root).as_posix()
            raise ValueError(f"{rel}: resolves outside the repository")
    return sorted(found)


def fingerprint(root: Path, files: list[Path]) -> str:
    """Hash of this tool and every indexed file, so any edit, move or upgrade is noticed."""
    digest = hashlib.sha256(Path(__file__).read_bytes())
    for path in files:
        if path.name not in RESERVED:
            data = path.read_bytes()
            digest.update(f"\0{path.relative_to(root).as_posix()}\0{len(data)}\0".encode() + data)
    return digest.hexdigest()


def build(root: Path) -> dict:
    root = root.resolve()
    files = source_files(root)
    stamp = fingerprint(root, files)  # before parsing: an edit made mid-build is caught next time
    docs, aliases, doc_rows, rows = {}, {}, [], []
    for path in files:
        rel = path.relative_to(root).as_posix()
        if path.name in RESERVED:
            match = FRONTMATTER.match(path.read_text(encoding="utf-8-sig"))
            if match and re.search(r"^id[ \t]*:", match.group(1), re.MULTILINE):
                raise ValueError(f"{rel}: index.md and log.md are reserved and never indexed; "
                                 "rename the file to index it")
            continue
        meta, body = parse_document(path)
        key = meta["id"]
        if key in docs:
            raise ValueError(f"Duplicate id: {key}")
        found = sections(body)
        docs[key] = {"path": rel, "title": meta["title"], "summary": meta["summary"],
                     "tags": meta["tags"], "related": meta["related"],
                     "sections": [[section.slug, section.heading_path] for section in found]}
        for alias in meta["aliases"]:
            alias = alias.strip().casefold()
            if not alias or alias in aliases:
                raise ValueError(f"Empty or duplicate alias: {alias!r}")
            aliases[alias] = key
        doc_rows.append((key, rel, meta["title"], " ".join(meta["tags"] + meta["aliases"]),
                         meta["summary"]))
        for section in found:
            rows.append((key, rel, meta["title"], section.heading_path, section.slug,
                         section.content))
    for key, entry in docs.items():
        if key in aliases and aliases[key] != key:
            raise ValueError(f"ID conflicts with alias: {key}")
        for related in entry["related"]:
            if related not in docs:
                raise ValueError(f"Unknown related id {related!r} in {key}")
    index = {"by_id": docs, "by_alias": aliases, "fingerprint": stamp}
    index_path, db_path = locations(root)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_db = db_path.with_suffix(f".{os.getpid()}.tmp")  # per process: rebuilds may overlap
    tmp_json = index_path.with_suffix(f".{os.getpid()}.tmp")
    try:
        tmp_db.unlink(missing_ok=True)
        with closing(sqlite3.connect(tmp_db)) as conn:
            # Document fields are indexed once in `docs`, not copied onto every section, so a
            # matching summary cannot turn all of a document's sections into hits.
            conn.execute("CREATE VIRTUAL TABLE docs USING fts5(id UNINDEXED, path UNINDEXED, "
                         "title, keywords, summary, tokenize='porter unicode61')")
            conn.execute("CREATE VIRTUAL TABLE sections USING fts5(id UNINDEXED, path UNINDEXED, "
                         "title UNINDEXED, heading, slug UNINDEXED, content, "
                         "tokenize='porter unicode61')")
            conn.executemany("INSERT INTO docs VALUES (?, ?, ?, ?, ?)", doc_rows)
            conn.executemany("INSERT INTO sections VALUES (?, ?, ?, ?, ?, ?)", rows)
            conn.commit()
        tmp_json.write_text(json.dumps(index, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                            encoding="utf-8")
        os.replace(tmp_db, db_path)
        os.replace(tmp_json, index_path)
    finally:
        tmp_db.unlink(missing_ok=True)
        tmp_json.unlink(missing_ok=True)
    return {"documents": len(docs), "sections": len(rows)}


def load_index(root: Path) -> dict:
    path, _ = locations(root)
    if not path.is_file():
        raise ValueError("Index missing; run 'build' first")
    return json.loads(path.read_text(encoding="utf-8"))


def ensure_index(root: Path) -> dict:
    """Load the index, rebuilding it first if a knowledge file or this tool changed."""
    root = root.resolve()
    index_path, db_path = locations(root)
    try:
        index = json.loads(index_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):  # missing or unreadable: rebuild
        index = {}
    if not db_path.is_file() or index.get("fingerprint") != fingerprint(root, source_files(root)):
        build(root)
        index = load_index(root)
    return index


def list_documents(index: dict) -> list[dict]:
    """Every document's id, path, title and summary, sorted by id."""
    return [{"id": key, "path": entry["path"], "title": entry["title"],
             "summary": entry["summary"]} for key, entry in sorted(index["by_id"].items())]


def write_catalog(root: Path, index: dict) -> str:
    """Write knowledge/index.md, a catalog for people browsing the repository.

    Returns "updated" or "unchanged". A hand-written index.md (one without the generated
    marker) is never overwritten, and "hand-written" is returned instead.
    """
    lines = [f"{CATALOG_MARK}; edit the documents, not this file. -->", "# Knowledge index", ""]
    for doc in list_documents(index):
        link = doc["path"].removeprefix("knowledge/")
        if any(char in link for char in " ()"):
            link = f"<{link}>"
        title = one_line(doc["title"]).replace("[", "\\[").replace("]", "\\]")
        lines.append(f"- [{title}]({link}) (`{doc['id']}`): {one_line(doc['summary'])}")
    text = "\n".join(lines) + "\n"
    target = root / "knowledge" / "index.md"
    if target.exists():
        current = target.read_text(encoding="utf-8-sig")
        if not current.startswith(CATALOG_MARK):
            return "hand-written"
        if current == text:
            return "unchanged"
    target.write_text(text, encoding="utf-8")
    return "updated"


def resolve(index: dict, name: str) -> str:
    """The document id for an id, an alias, or an indexed file path."""
    key = index["by_alias"].get(name.casefold(), name.casefold())
    if key not in index["by_id"]:  # a path, as printed in results and citations
        key = next((doc for doc, entry in index["by_id"].items() if entry["path"] == name), key)
    if key not in index["by_id"]:
        raise ValueError(f"Unknown id, alias or path: {name}")
    return key


def get(root: Path, ref: str, *, summary: bool = False, section: str | None = None,
        index: dict | None = None) -> dict:
    """A document's metadata (summary=True), its whole body, or one section.

    `ref` is an id, alias or path, optionally followed by `#slug` as search prints it.
    """
    if index is None:
        index = load_index(root)
    name, _, slug = ref.partition("#")
    if slug and section is not None:
        raise ValueError("give the section either as <id>#<slug> or with --section, not both")
    section = slug or section
    if summary and section:
        raise ValueError("--summary and a section are mutually exclusive")
    key = resolve(index, name)
    entry = index["by_id"][key]
    if summary:
        return {"id": key, **entry}
    path = (root.resolve() / entry["path"]).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError("Unsafe indexed path")
    if not path.is_file():
        raise ValueError(f"{entry['path']} no longer exists; the index is stale (run 'build')")
    _, body = parse_document(path)
    result = {"id": key, "path": entry["path"], "title": entry["title"]}
    if section:
        found = find_section(sections(body), section)
        result.update(slug=found.slug, heading=found.heading_path)
        body = found.content
    return {**result, "content": body}


def find_section(found: list[Section], wanted: str) -> Section:
    """The section with this exact slug, or else the only one with this heading.

    Slugs match exactly (they are lowercase, as search prints them). Headings, or heading
    paths such as "Postgres > Configuration", match case-insensitively, so a heading that
    two sections share is reported as ambiguous instead of guessed.
    """
    for section in found:
        if section.slug == wanted:
            return section
    named = [section for section in found
             if wanted.casefold() in (section.heading.casefold(), section.heading_path.casefold())]
    if len(named) == 1:
        return named[0]
    if named:
        raise ValueError(f"Section {wanted!r} is ambiguous; use a slug: "
                         + ", ".join(section.slug for section in named))
    raise ValueError(f"Unknown section {wanted!r}; sections: "
                     + ", ".join(section.slug for section in found))


def search(root: Path, query: str, limit: int = 5, match_all: bool = False) -> list[dict]:
    """The best matches, best first. A higher score is a better match.

    A section is returned only when its own heading path or text matches: any query word, or
    every one with `match_all`. A match on its document's title, tags or summary raises its
    score; a document that matches only there is returned once, with its summary instead.
    """
    _, db_path = locations(root)
    if not db_path.is_file():
        raise ValueError("Search database missing; run 'build' first")
    tokens = WORD.findall(query.casefold())[:24]
    if not tokens:
        return []
    joiner = " AND " if match_all else " OR "
    expression = joiner.join('"' + token.replace('"', '""') + '"' for token in tokens)
    # bm25() weights follow each table's column order; a lower bm25 is a better match.
    with closing(sqlite3.connect(db_path)) as conn:
        matched_docs = {row[0]: row for row in conn.execute(
            "SELECT id, path, title, summary, bm25(docs, 0, 0, 6, 5, 4) FROM docs "
            "WHERE docs MATCH ?", (expression,))}

        def doc_score(doc: str) -> float:
            return matched_docs[doc][4] if doc in matched_docs else 0.0

        conn.create_function("doc_score", 1, doc_score, deterministic=True)
        boost = " + doc_score(id)" if matched_docs else ""  # skip the per-row call if unused
        rows = conn.execute(
            "SELECT id, path, title, heading, slug, snippet(sections, 5, '', '', '...', 18), "
            f"bm25(sections, 0, 0, 0, 4, 0, 1){boost} AS score FROM sections "
            "WHERE sections MATCH ? ORDER BY score LIMIT ?", (expression, limit)).fetchall()
        doc_only = set(matched_docs) - {row[0] for row in rows}
        if len(rows) == limit:  # a document hit that cannot beat the last section hit is cut
            doc_only = {doc for doc in doc_only if matched_docs[doc][4] < rows[-1][6]}
        if doc_only:  # drop documents that do have matching sections, just not in the top hits
            doc_only -= {doc for (doc,) in conn.execute(
                "SELECT DISTINCT id FROM sections WHERE sections MATCH ?", (expression,))}
    hits = [{"id": doc, "path": path, "title": title, "heading": heading, "slug": slug,
             "snippet": one_line(snippet), "score": score}
            for doc, path, title, heading, slug, snippet, score in rows]
    hits += [{"id": doc, "path": path, "title": title, "summary": summary, "score": score}
             for doc, path, title, summary, score in matched_docs.values() if doc in doc_only]
    hits.sort(key=lambda hit: hit["score"])
    return [{**hit, "score": round(-hit["score"], 3)} for hit in hits[:limit]]


def qmd_command() -> str:
    """The QMD executable: $KB_QMD if set, otherwise `qmd` on PATH."""
    found = os.environ.get("KB_QMD") or shutil.which("qmd")
    if not found:
        raise ValueError("--semantic needs QMD (https://github.com/tobi/qmd, Node.js 22+); "
                         "install it with 'npm install -g @tobilu/qmd' or set KB_QMD")
    return found


def run_qmd(qmd: str, name: str, *args: str, allow: str = "") -> str:
    """Run a QMD command on kb's index; a failure raises unless its message contains `allow`."""
    done = subprocess.run([qmd, "--index", name, *args], capture_output=True, text=True,
                          encoding="utf-8", check=False)
    message = (done.stderr + done.stdout).strip()
    if done.returncode and not (allow and allow in message):
        raise ValueError(f"qmd {args[0]} failed: {message[-500:]}")
    return done.stdout


def sync_qmd(root: Path, index: dict, qmd: str) -> str:
    """The name of this repository's QMD index, refreshed first if the knowledge changed.

    QMD embeds chunks of about 900 tokens, which would merge short sections, so every section
    is written to its own file under .knowledge/sections/ and QMD indexes that folder. QMD
    keeps the index and its embedding model in its own cache; it re-embeds only changed text.
    """
    name = "kb-" + hashlib.sha256(str(root).encode()).hexdigest()[:12]
    folder, state = root / ".knowledge" / "sections", root / ".knowledge" / "qmd.json"
    current = {"index": name, "fingerprint": index["fingerprint"]}
    try:
        if json.loads(state.read_text(encoding="utf-8")) == current:
            return name
    except (OSError, ValueError):  # never synced, or unreadable: sync
        pass
    shutil.rmtree(folder, ignore_errors=True)
    for key, entry in index["by_id"].items():
        if ".." in key.split("/"):  # ids name folders here; keep every file inside `folder`
            raise ValueError(f"{entry['path']}: --semantic cannot use the id {key!r}")
        _, body = parse_document(root / entry["path"])
        for section in sections(body):
            target = folder / key / f"{section.slug}.md"
            target.parent.mkdir(parents=True, exist_ok=True)
            text = f"# {entry['title']} > {section.heading_path}\n\n{section.content}\n"
            target.write_text(text, encoding="utf-8")
    run_qmd(qmd, name, "collection", "add", str(folder), "--name", QMD_COLLECTION,
            allow="already exists")
    run_qmd(qmd, name, "update")
    run_qmd(qmd, name, "embed")
    state.write_text(json.dumps(current) + "\n", encoding="utf-8")
    return name


def semantic_search(root: Path, query: str, limit: int = 5,
                    index: dict | None = None) -> list[dict]:
    """QMD's vector search over the sections, merged with sections holding every query word.

    Each ranked list adds 1 / (60 + rank) to a hit's score (reciprocal rank fusion), so a
    section found both by its words and by its meaning ranks above one found only one way.
    Requiring every word keeps sections that share only a stray word with a reworded question
    from outranking the ones found by meaning. A section found only by meaning gets the start
    of its text as its snippet.
    """
    root = root.resolve()
    index = index or ensure_index(root)
    qmd = qmd_command()
    name = sync_qmd(root, index, qmd)
    depth = max(limit, 10)
    lexical = [hit for hit in search(root, query, depth, match_all=True) if "slug" in hit]
    fused = {(hit["id"], hit["slug"]): {**hit, "score": 1 / (RRF_K + rank)}
             for rank, hit in enumerate(lexical, 1)}
    text = " ".join(query.replace('"', " ").split())  # a QMD query line: one line, no quotes
    output = run_qmd(qmd, name, "query", f"vec: {text}", "--no-rerank", "-n", str(depth),
                     "-c", QMD_COLLECTION, "--json") if text else ""
    rows = json.loads(output) if output.lstrip().startswith("[") else []  # or "No results"
    for rank, row in enumerate(rows, 1):
        path = unquote(row["file"].split("?")[0]).split("/", 3)[-1]  # qmd://sections/<path>
        doc, _, slug = path.removesuffix(".md").rpartition("/")
        headings = dict(index["by_id"].get(doc, {}).get("sections", []))
        if slug not in headings:  # stale export or unknown file
            continue
        if (doc, slug) not in fused:
            words = get(root, f"{doc}#{slug}", index=index)["content"].split()
            fused[(doc, slug)] = {"id": doc, "path": index["by_id"][doc]["path"],
                                  "title": index["by_id"][doc]["title"],
                                  "heading": headings[slug], "slug": slug, "score": 0.0,
                                  "snippet": " ".join(words[:18]) + ("..." if words[18:] else "")}
        fused[(doc, slug)]["score"] += 1 / (RRF_K + rank)
    ranked = sorted(fused.values(), key=lambda hit: -hit["score"])[:limit]
    return [{**hit, "score": round(hit["score"], 4)} for hit in ranked]


def one_line(text: str) -> str:
    return " ".join(text.split())


def group_hits(hits: list[dict]) -> list[dict]:
    """Hits grouped by document, so a document's path and title are printed once."""
    groups: dict[str, dict] = {}
    for hit in hits:
        group = groups.setdefault(hit["id"], {"id": hit["id"], "path": hit["path"],
                                              "title": hit["title"], "sections": []})
        if "slug" in hit:
            group["sections"].append({"ref": f"{hit['id']}#{hit['slug']}",
                                      "heading": hit["heading"], "snippet": hit["snippet"],
                                      "score": hit["score"]})
        else:  # matched on the document's title, tags or summary only
            group.update(summary=hit["summary"], score=hit["score"])
    return list(groups.values())


def render_search(groups: list[dict]) -> str:
    """A header line per document, then one `ref  heading: snippet` line per section.

    A document that matched only on its title, tags or summary gets an `id  summary` line.
    """
    if not groups:
        return "no matches"
    lines = []
    for group in groups:
        lines.append(f"{group['path']}  {one_line(group['title'])}")
        if "summary" in group:
            lines.append(f"  {group['id']}  {one_line(group['summary'])}")
        lines += [f"  {s['ref']}  {s['heading']}: {s['snippet']}" for s in group["sections"]]
    return "\n".join(lines)


def render_list(documents: list[dict]) -> str:
    """One `id  title: summary` line per document."""
    return "\n".join(f"{doc['id']}  {one_line(doc['title'])}: {one_line(doc['summary'])}"
                     for doc in documents) or "no documents"


def render_get(result: dict) -> str:
    if "content" not in result:  # --summary
        lines = [f"{result['id']}  {one_line(result['title'])}", f"path: {result['path']}",
                 f"summary: {one_line(result['summary'])}"]
        lines += [f"{field}: {', '.join(result[field])}"
                  for field in ("tags", "related") if result[field]]
        if result.get("sections"):
            lines.append("sections:")
            lines += [f"  {result['id']}#{slug}  {heading}" for slug, heading in result["sections"]]
        return "\n".join(lines)
    where = result["path"] + (f"#{result['slug']}" if "slug" in result else "")
    label = one_line(result["title"]) + (f" > {result['heading']}" if "heading" in result else "")
    return f"{where}  {label}\n\n{result['content']}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    shared = argparse.ArgumentParser(add_help=False)
    shared.add_argument("--json", action="store_true", help="print compact JSON instead of text")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", parents=[shared],
                        help="validate the knowledge files, rebuild the index and "
                             "refresh knowledge/index.md")
    commands.add_parser("list", parents=[shared],
                        help="one line per document: id, title and summary")
    q = commands.add_parser("search", parents=[shared], help="find the best-matching sections")
    q.add_argument("query")
    q.add_argument("--limit", type=int, default=5)
    q.add_argument("--semantic", action="store_true",
                   help="also match by meaning, using QMD's vector search (QMD must be installed)")
    g = commands.add_parser("get", parents=[shared],
                            help="print a document, its summary, or one section")
    g.add_argument("ref", help="id, alias or path, optionally with #slug, e.g. auth#refresh-tokens")
    g.add_argument("--summary", action="store_true", help="metadata only")
    g.add_argument("--section", help="a section slug, or a heading only one section has")
    args = parser.parse_args(argv)
    try:
        if args.command == "build":
            output = build(args.root)
            output["catalog"] = write_catalog(args.root.resolve(), load_index(args.root))
            text = (f"indexed {output['documents']} documents, {output['sections']} sections; "
                    f"knowledge/index.md {output['catalog']}")
        elif args.command == "list":
            output = list_documents(ensure_index(args.root))
            text = render_list(output)
        elif args.command == "search":
            if not 1 <= args.limit <= 100:
                raise ValueError("--limit must be between 1 and 100")
            index = ensure_index(args.root)
            hits = (semantic_search(args.root, args.query, args.limit, index) if args.semantic
                    else search(args.root, args.query, args.limit))
            output = group_hits(hits)
            text = render_search(output)
        else:
            output = get(args.root, args.ref, summary=args.summary, section=args.section,
                         index=ensure_index(args.root))
            text = render_get(output)
        print(json.dumps(output, ensure_ascii=False, separators=(",", ":")) if args.json else text)
        return 0
    except (ValueError, OSError, sqlite3.Error) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
